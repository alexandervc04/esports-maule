-- REPORTE 2: RANKING DE JUGADORES MVP
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_REPORTE_RANKING_MVP (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT J.NICKNAME,
               SUM(D.KILLS) AS KILLS,
               SUM(D.DEATHS) AS DEATHS,
               SUM(D.ASSISTS) AS ASSISTS,
               AV_JP_RM_BE_FN_CALCULAR_RATIO_KDA(
                   SUM(D.KILLS), SUM(D.DEATHS), SUM(D.ASSISTS)
               ) AS RATIO_KDA,
               SUM(CASE WHEN D.ES_MVP = 'S' THEN 1 ELSE 0 END) AS VECES_MVP,
               SUM(CASE WHEN P.ID_GANADOR = J.ID_EQUIPO THEN 1 ELSE 0 END) AS VICTORIAS
        FROM AV_JP_RM_BE_JUGADOR J
        JOIN AV_JP_RM_BE_DETALLE_PARTIDA_JUGADOR D ON D.ID_JUGADOR = J.ID_JUGADOR
        JOIN AV_JP_RM_BE_PARTIDA P ON P.ID_PARTIDA = D.ID_PARTIDA
        GROUP BY J.ID_JUGADOR, J.NICKNAME, J.ID_EQUIPO
        ORDER BY RATIO_KDA DESC, VECES_MVP DESC;
END;
/

-- REPORTE 3: OCUPACION DE SEDES Y BALANCE
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_REPORTE_OCUPACION_SEDES (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT T.NOMBRE AS TORNEO,
               S.NOMBRE AS SEDE,
               T.CUPO_MAXIMO,
               COUNT(I.ID_INSCRIPCION) AS INSCRITOS,
               ROUND((COUNT(I.ID_INSCRIPCION) * 100) / T.CUPO_MAXIMO, 2) AS OCUPACION_PORCENTAJE,
               NVL(SUM(I.MONTO_PAGADO), 0)
               + NVL((
                    SELECT SUM(TP.MONTO_APORTE)
                    FROM AV_JP_RM_BE_TORNEO_PATROCINADOR TP
                    WHERE TP.ID_TORNEO = T.ID_TORNEO
                 ), 0)
               - T.PREMIO_TOTAL AS BALANCE_ESTIMADO
        FROM AV_JP_RM_BE_TORNEO T
        JOIN AV_JP_RM_BE_SEDE S ON S.ID_SEDE = T.ID_SEDE
        LEFT JOIN AV_JP_RM_BE_INSCRIPCION I
               ON I.ID_TORNEO = T.ID_TORNEO
              AND I.ESTADO = 'CONFIRMADA'
        GROUP BY T.ID_TORNEO, T.NOMBRE, S.NOMBRE, T.CUPO_MAXIMO, T.PREMIO_TOTAL
        ORDER BY OCUPACION_PORCENTAJE DESC;
END;
