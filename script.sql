-- GESTOR 3: GENERACION DE FIXTURE MEDIANTE CURSOR EXPLICITO
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_GENERAR_FIXTURE (
    P_ID_TORNEO IN NUMBER
) IS
    CURSOR C_EQUIPOS IS
        SELECT ID_EQUIPO
        FROM AV_JP_RM_BE_INSCRIPCION
        WHERE ID_TORNEO = P_ID_TORNEO
          AND ESTADO = 'CONFIRMADA'
        ORDER BY ID_INSCRIPCION;

    V_EQUIPO_LOCAL NUMBER := NULL;
    V_EQUIPO_ACTUAL NUMBER;
    V_FECHA_INICIO DATE;
    V_CONTADOR NUMBER := 0;
    V_EXISTENTES NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_EXISTENTES
    FROM AV_JP_RM_BE_PARTIDA
    WHERE ID_TORNEO = P_ID_TORNEO;

    IF V_EXISTENTES > 0 THEN
        RAISE_APPLICATION_ERROR(-20030, 'EL TORNEO YA TIENE FIXTURE');
    END IF;

    SELECT FECHA_INICIO
    INTO V_FECHA_INICIO
    FROM AV_JP_RM_BE_TORNEO
    WHERE ID_TORNEO = P_ID_TORNEO;

    OPEN C_EQUIPOS;

    LOOP
        FETCH C_EQUIPOS INTO V_EQUIPO_ACTUAL;
        EXIT WHEN C_EQUIPOS%NOTFOUND;

        IF V_EQUIPO_LOCAL IS NULL THEN
            V_EQUIPO_LOCAL := V_EQUIPO_ACTUAL;
        ELSE
            V_CONTADOR := V_CONTADOR + 1;

            INSERT INTO AV_JP_RM_BE_PARTIDA (
                ID_PARTIDA, ID_TORNEO, RONDA, ID_EQUIPO_LOCAL,
                ID_EQUIPO_VISITA, FECHA_HORA, ESTADO
            ) VALUES (
                AV_JP_RM_BE_SEQ_PARTIDA.NEXTVAL, P_ID_TORNEO, 1,
                V_EQUIPO_LOCAL, V_EQUIPO_ACTUAL,
                V_FECHA_INICIO + (V_CONTADOR / 24), 'PROGRAMADA'
            );

            V_EQUIPO_LOCAL := NULL;
        END IF;
    END LOOP;

    CLOSE C_EQUIPOS;

    IF V_EQUIPO_LOCAL IS NOT NULL THEN
        V_CONTADOR := V_CONTADOR + 1;

        INSERT INTO AV_JP_RM_BE_PARTIDA (
            ID_PARTIDA, ID_TORNEO, RONDA, ID_EQUIPO_LOCAL,
            ID_EQUIPO_VISITA, FECHA_HORA, ID_GANADOR, ESTADO
        ) VALUES (
            AV_JP_RM_BE_SEQ_PARTIDA.NEXTVAL, P_ID_TORNEO, 1,
            V_EQUIPO_LOCAL, NULL,
            V_FECHA_INICIO + (V_CONTADOR / 24), V_EQUIPO_LOCAL, 'BYE'
        );
    END IF;

    UPDATE AV_JP_RM_BE_TORNEO
    SET ESTADO = 'EN_CURSO'
    WHERE ID_TORNEO = P_ID_TORNEO;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

-- GESTOR 4: REGISTRO DE RESULTADOS
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_REGISTRAR_RESULTADO (
    P_ID_PARTIDA IN NUMBER,
    P_ID_ARBITRO IN NUMBER,
    P_PUNTAJE_LOCAL IN NUMBER,
    P_PUNTAJE_VISITA IN NUMBER
) IS
    V_ID_TORNEO NUMBER;
    V_LOCAL NUMBER;
    V_VISITA NUMBER;
    V_PUNTOS_VICTORIA NUMBER;
    V_PUNTOS_EMPATE NUMBER;
    V_GANADOR NUMBER;
BEGIN
    SELECT ID_TORNEO, ID_EQUIPO_LOCAL, ID_EQUIPO_VISITA
    INTO V_ID_TORNEO, V_LOCAL, V_VISITA
    FROM AV_JP_RM_BE_PARTIDA
    WHERE ID_PARTIDA = P_ID_PARTIDA;

    IF V_VISITA IS NULL THEN
        RAISE_APPLICATION_ERROR(-20040, 'UNA PARTIDA BYE NO REQUIERE RESULTADO');
    END IF;

    SELECT F.PUNTOS_VICTORIA, F.PUNTOS_EMPATE
    INTO V_PUNTOS_VICTORIA, V_PUNTOS_EMPATE
    FROM AV_JP_RM_BE_TORNEO T
    JOIN AV_JP_RM_BE_FORMATO_TORNEO F ON F.ID_FORMATO = T.ID_FORMATO
    WHERE T.ID_TORNEO = V_ID_TORNEO;

    IF P_PUNTAJE_LOCAL > P_PUNTAJE_VISITA THEN
        V_GANADOR := V_LOCAL;
    ELSIF P_PUNTAJE_VISITA > P_PUNTAJE_LOCAL THEN
        V_GANADOR := V_VISITA;
    ELSE
        V_GANADOR := NULL;
    END IF;

    UPDATE AV_JP_RM_BE_PARTIDA
    SET ID_ARBITRO = P_ID_ARBITRO,
        PUNTAJE_LOCAL = P_PUNTAJE_LOCAL,
        PUNTAJE_VISITA = P_PUNTAJE_VISITA,
        ID_GANADOR = V_GANADOR,
        ESTADO = 'JUGADA'
    WHERE ID_PARTIDA = P_ID_PARTIDA;

    IF V_GANADOR IS NULL THEN
        UPDATE AV_JP_RM_BE_INSCRIPCION
        SET PUNTOS = PUNTOS + V_PUNTOS_EMPATE
        WHERE ID_TORNEO = V_ID_TORNEO
          AND ID_EQUIPO IN (V_LOCAL, V_VISITA)
          AND ESTADO = 'CONFIRMADA';
    ELSE
        UPDATE AV_JP_RM_BE_INSCRIPCION
        SET PUNTOS = PUNTOS + V_PUNTOS_VICTORIA
        WHERE ID_TORNEO = V_ID_TORNEO
          AND ID_EQUIPO = V_GANADOR
          AND ESTADO = 'CONFIRMADA';
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

-- GESTOR 4: REGISTRO DE KDA POR JUGADOR
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_REGISTRAR_KDA (
    P_ID_PARTIDA IN NUMBER,
