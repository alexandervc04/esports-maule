-- MANTENEDOR USUARIO Y PERFILES
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_USUARIO_GUARDAR (
    P_ID IN OUT NUMBER,
    P_USERNAME IN VARCHAR2,
    P_CONTRASENA IN VARCHAR2,
    P_NOMBRE IN VARCHAR2,
    P_EMAIL IN VARCHAR2,
    P_PERFIL IN VARCHAR2,
    P_ESTADO IN VARCHAR2
) IS
BEGIN
    IF P_ID IS NULL OR P_ID = 0 THEN
        P_ID := AV_JP_RM_BE_SEQ_USUARIO.NEXTVAL;

        INSERT INTO AV_JP_RM_BE_USUARIO (
            ID_USUARIO, USERNAME, PASSWORD_HASH, NOMBRE, EMAIL, PERFIL, ESTADO
        ) VALUES (
            P_ID,
            UPPER(TRIM(P_USERNAME)),
            RAWTOHEX(STANDARD_HASH(P_CONTRASENA, 'SHA256')),
            UPPER(TRIM(P_NOMBRE)),
            UPPER(TRIM(P_EMAIL)),
            UPPER(P_PERFIL),
            UPPER(P_ESTADO)
        );
    ELSE
        UPDATE AV_JP_RM_BE_USUARIO
        SET USERNAME = UPPER(TRIM(P_USERNAME)),
            PASSWORD_HASH = CASE
                WHEN P_CONTRASENA IS NULL THEN PASSWORD_HASH
                ELSE RAWTOHEX(STANDARD_HASH(P_CONTRASENA, 'SHA256'))
            END,
            NOMBRE = UPPER(TRIM(P_NOMBRE)),
            EMAIL = UPPER(TRIM(P_EMAIL)),
            PERFIL = UPPER(P_PERFIL),
            ESTADO = UPPER(P_ESTADO)
        WHERE ID_USUARIO = P_ID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'USUARIO NO ENCONTRADO');
        END IF;
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_USUARIO_LISTAR (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
