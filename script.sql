CREATE OR REPLACE FUNCTION AV_JP_RM_BE_FN_VALIDAR_CUPOS_TORNEO (
    P_ID_TORNEO IN NUMBER
) RETURN NUMBER IS
    V_CUPO NUMBER;
    V_INSCRITOS NUMBER;
BEGIN
    SELECT CUPO_MAXIMO
    INTO V_CUPO
    FROM AV_JP_RM_BE_TORNEO
    WHERE ID_TORNEO = P_ID_TORNEO;

    SELECT COUNT(*)
    INTO V_INSCRITOS
    FROM AV_JP_RM_BE_INSCRIPCION
    WHERE ID_TORNEO = P_ID_TORNEO
      AND ESTADO = 'CONFIRMADA';

    IF V_INSCRITOS < V_CUPO THEN
        RETURN 1;
    END IF;

    RETURN 0;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;
/

CREATE OR REPLACE FUNCTION AV_JP_RM_BE_FN_CALCULAR_RATIO_KDA (
    P_KILLS IN NUMBER,
    P_DEATHS IN NUMBER,
    P_ASSISTS IN NUMBER
) RETURN NUMBER IS
BEGIN
    RETURN ROUND((NVL(P_KILLS, 0) + NVL(P_ASSISTS, 0)) / GREATEST(NVL(P_DEATHS, 0), 1), 2);
END;
/

CREATE OR REPLACE FUNCTION AV_JP_RM_BE_FN_VERIFICAR_ESTADO_JUGADOR (
    P_ID_JUGADOR IN NUMBER
) RETURN VARCHAR2 IS
    V_SANCIONES NUMBER;
    V_ESTADO VARCHAR2(12);
BEGIN
    SELECT COUNT(*)
    INTO V_SANCIONES
    FROM AV_JP_RM_BE_SANCION
    WHERE ID_JUGADOR = P_ID_JUGADOR
      AND ESTADO = 'VIGENTE'
      AND TIPO = 'SUSPENSION'
      AND (FECHA_FIN_SUSPENSION IS NULL OR FECHA_FIN_SUSPENSION >= SYSDATE);

    IF V_SANCIONES > 0 THEN
        RETURN 'SANCIONADO';
    END IF;

    SELECT ESTADO
    INTO V_ESTADO
    FROM AV_JP_RM_BE_JUGADOR
    WHERE ID_JUGADOR = P_ID_JUGADOR;

    RETURN V_ESTADO;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'NO_EXISTE';
END;
/

