CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_LOGIN (
    P_USERNAME IN VARCHAR2,
    P_CONTRASENA IN VARCHAR2,
    P_ID_USUARIO OUT NUMBER,
    P_NOMBRE OUT VARCHAR2,
    P_PERFIL OUT VARCHAR2,
    P_RESULTADO OUT NUMBER
) IS
BEGIN
    SELECT ID_USUARIO, NOMBRE, PERFIL
    INTO P_ID_USUARIO, P_NOMBRE, P_PERFIL
    FROM AV_JP_RM_BE_USUARIO
    WHERE USERNAME = UPPER(TRIM(P_USERNAME))
      AND PASSWORD_HASH = RAWTOHEX(STANDARD_HASH(P_CONTRASENA, 'SHA256'))
      AND ESTADO = 'ACTIVO';

    P_RESULTADO := 1;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        P_ID_USUARIO := NULL;
        P_NOMBRE := NULL;
        P_PERFIL := NULL;
        P_RESULTADO := 0;
END;
/

