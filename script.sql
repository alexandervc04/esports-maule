-- GESTOR 2: INSCRIPCION DE EQUIPOS Y ROSTER
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_INSCRIBIR_EQUIPO (
    P_ID_TORNEO IN NUMBER,
    P_ID_EQUIPO IN NUMBER,
    P_MONTO_PAGADO IN NUMBER,
    P_ID_INSCRIPCION OUT NUMBER
) IS
    CURSOR C_JUGADORES IS
        SELECT ID_JUGADOR
        FROM AV_JP_RM_BE_JUGADOR
        WHERE ID_EQUIPO = P_ID_EQUIPO
          AND ESTADO = 'ACTIVO'
        ORDER BY ID_JUGADOR;

    V_JUGADORES NUMBER := 0;
BEGIN
    IF AV_JP_RM_BE_FN_VALIDAR_CUPOS_TORNEO(P_ID_TORNEO) = 0 THEN
        RAISE_APPLICATION_ERROR(-20020, 'TORNEO SIN CUPOS DISPONIBLES');
    END IF;

    P_ID_INSCRIPCION := AV_JP_RM_BE_SEQ_INSCRIPCION.NEXTVAL;

    INSERT INTO AV_JP_RM_BE_INSCRIPCION (
        ID_INSCRIPCION, ID_TORNEO, ID_EQUIPO, MONTO_PAGADO, PUNTOS, ESTADO
    ) VALUES (
        P_ID_INSCRIPCION, P_ID_TORNEO, P_ID_EQUIPO, P_MONTO_PAGADO, 0, 'CONFIRMADA'
    );

    FOR R IN C_JUGADORES LOOP
        INSERT INTO AV_JP_RM_BE_ROSTER (ID_INSCRIPCION, ID_JUGADOR)
        VALUES (P_ID_INSCRIPCION, R.ID_JUGADOR);

        V_JUGADORES := V_JUGADORES + 1;
    END LOOP;

    IF V_JUGADORES = 0 THEN
        RAISE_APPLICATION_ERROR(-20021, 'EL EQUIPO NO TIENE JUGADORES ACTIVOS');
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
