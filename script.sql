-- REPORTE 1: DEMANDA Y RECAUDACION POR VIDEOJUEGO
CREATE OR REPLACE PROCEDURE AV_JP_RM_BE_SP_REPORTE_DEMANDA_JUEGO (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT V.NOMBRE AS VIDEOJUEGO,
               COUNT(DISTINCT T.ID_TORNEO) AS TORNEOS,
               COUNT(I.ID_INSCRIPCION) AS EQUIPOS_INSCRITOS,
               NVL(SUM(I.MONTO_PAGADO), 0) AS RECAUDACION
        FROM AV_JP_RM_BE_VIDEOJUEGO V
        LEFT JOIN AV_JP_RM_BE_TORNEO T ON T.ID_VIDEOJUEGO = V.ID_VIDEOJUEGO
        LEFT JOIN AV_JP_RM_BE_INSCRIPCION I
               ON I.ID_TORNEO = T.ID_TORNEO
              AND I.ESTADO = 'CONFIRMADA'
        GROUP BY V.NOMBRE
        ORDER BY RECAUDACION DESC;
END;
