CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_LOGIN (
    P_EMAIL      IN  VARCHAR2,
    P_CONTRASENA IN  VARCHAR2,
    P_CURSOR     OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT U.ID_USUARIO, U.RUT, U.NOMBRE, U.EMAIL, P.ID_PERFIL, P.NOMBRE AS PERFIL
        FROM AV_JP_RM_BE_USUARIOS U
        INNER JOIN AV_JP_RM_BE_PERFILES P ON U.ID_PERFIL = P.ID_PERFIL
        WHERE LOWER(U.EMAIL) = LOWER(P_EMAIL)
          AND U.CONTRASENA = P_CONTRASENA;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20002, 'ERROR AL VALIDAR ACCESO: ' || SQLERRM);
END SP_AV_JP_RM_BE_LOGIN;
/

-- MANTENEDOR 1: JUEGOS
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_MANT_JUEGOS (
    P_OPCION   IN VARCHAR2,
    P_ID_JUEGO IN NUMBER,
    P_NOMBRE   IN VARCHAR2,
    P_GENERO   IN VARCHAR2,
    P_VERSION  IN VARCHAR2
) IS
BEGIN
    IF UPPER(P_OPCION) = 'INSERT' THEN
        INSERT INTO AV_JP_RM_BE_JUEGOS (ID_JUEGO, NOMBRE, GENERO, VERSION)
        VALUES (SEQ_AV_JP_RM_BE_JUEGOS.NEXTVAL, P_NOMBRE, P_GENERO, P_VERSION);
    ELSIF UPPER(P_OPCION) = 'UPDATE' THEN
        UPDATE AV_JP_RM_BE_JUEGOS
        SET NOMBRE = P_NOMBRE, GENERO = P_GENERO, VERSION = P_VERSION
        WHERE ID_JUEGO = P_ID_JUEGO;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20010, 'JUEGO NO ENCONTRADO.');
        END IF;
    ELSIF UPPER(P_OPCION) = 'DELETE' THEN
        DELETE FROM AV_JP_RM_BE_JUEGOS WHERE ID_JUEGO = P_ID_JUEGO;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20011, 'JUEGO NO ENCONTRADO PARA ELIMINAR.');
        END IF;
    ELSE
        RAISE_APPLICATION_ERROR(-20012, 'OPCIÓN INVÁLIDA. USE INSERT, UPDATE O DELETE.');
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'ERROR EN MANTENEDOR JUEGOS: ' || SQLERRM);
END SP_AV_JP_RM_BE_MANT_JUEGOS;
/

CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_LIST_JUEGOS (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT ID_JUEGO, NOMBRE, GENERO, VERSION
