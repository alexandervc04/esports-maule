-- GESTOR 1: INSCRIPCIÓN DE EQUIPOS A TORNEOS
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_GEST_INSCRIPCION (
    P_ID_TORNEO IN NUMBER,
    P_ID_EQUIPO IN NUMBER,
    P_ESTADO    IN VARCHAR2
) IS
    V_CUPOS_LIBRES NUMBER;
    V_YA_INSCRITO  NUMBER;
BEGIN
    V_CUPOS_LIBRES := FN_AV_JP_RM_BE_CUPOS_DISPONIBLES(P_ID_TORNEO);
    IF V_CUPOS_LIBRES < 0 THEN
        RAISE_APPLICATION_ERROR(-20021, 'EL TORNEO INDICADO NO EXISTE.');
    ELSIF V_CUPOS_LIBRES = 0 THEN
        RAISE_APPLICATION_ERROR(-20022, 'NO QUEDAN CUPOS DISPONIBLES EN ESTE TORNEO.');
    END IF;

    SELECT COUNT(*) INTO V_YA_INSCRITO
    FROM AV_JP_RM_BE_INSCRIPCIONES
    WHERE ID_TORNEO = P_ID_TORNEO AND ID_EQUIPO = P_ID_EQUIPO;

    IF V_YA_INSCRITO > 0 THEN
        RAISE_APPLICATION_ERROR(-20023, 'ESTE EQUIPO YA SE ENCUENTRA INSCRITO EN EL TORNEO.');
    END IF;

    INSERT INTO AV_JP_RM_BE_INSCRIPCIONES (ID_INSCRIPCION, FECHA, ESTADO, ID_TORNEO, ID_EQUIPO)
    VALUES (SEQ_AV_JP_RM_BE_INSCRIPCIONES.NEXTVAL, SYSDATE, UPPER(P_ESTADO), P_ID_TORNEO, P_ID_EQUIPO);
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'ERROR EN GESTOR INSCRIPCIÓN: ' || SQLERRM);
