CREATE OR REPLACE FUNCTION FN_AV_JP_RM_BE_CUPOS_DISPONIBLES (
    P_ID_TORNEO IN NUMBER
) RETURN NUMBER IS
    V_MAX_CUPOS NUMBER := 0;
    V_INSCRITOS NUMBER := 0;
BEGIN
    SELECT MAX_CUPOS INTO V_MAX_CUPOS
    FROM AV_JP_RM_BE_TORNEOS
    WHERE ID_TORNEO = P_ID_TORNEO;

    SELECT COUNT(*) INTO V_INSCRITOS
    FROM AV_JP_RM_BE_INSCRIPCIONES
    WHERE ID_TORNEO = P_ID_TORNEO
      AND UPPER(ESTADO) = 'CONFIRMADA';

    RETURN (V_MAX_CUPOS - V_INSCRITOS);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
    WHEN OTHERS THEN
        RETURN -2;
END FN_AV_JP_RM_BE_CUPOS_DISPONIBLES;
/

CREATE OR REPLACE FUNCTION FN_AV_JP_RM_BE_CALCULAR_KDA (
    P_KILLS   IN NUMBER,
    P_DEATHS  IN NUMBER,
    P_ASSISTS IN NUMBER
) RETURN NUMBER IS
    V_KDA NUMBER(10, 2);
BEGIN
    IF P_DEATHS <= 0 THEN
        V_KDA := P_KILLS + P_ASSISTS;
    ELSE
        V_KDA := ROUND((P_KILLS + P_ASSISTS) / P_DEATHS, 2);
    END IF;
    RETURN V_KDA;
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END FN_AV_JP_RM_BE_CALCULAR_KDA;
/

CREATE OR REPLACE FUNCTION FN_AV_JP_RM_BE_CONTAR_SANCIONES (
