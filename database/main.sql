CREATE OR REPLACE TRIGGER TRG_AV_JP_RM_BE_VAL_KDA_JUGADOR
BEFORE INSERT ON AV_JP_RM_BE_DETALLE_ESTADISTICAS_KDA
FOR EACH ROW
DECLARE
    V_SANCIONES NUMBER;
BEGIN
    V_SANCIONES := FN_AV_JP_RM_BE_CONTAR_SANCIONES(:NEW.ID_JUGADOR);
    IF V_SANCIONES >= 3 THEN
        RAISE_APPLICATION_ERROR(-20001, 'EL JUGADOR POSEE 3 O MÁS SANCIONES Y ESTÁ BLOQUEADO PARA REGISTRAR ESTADÍSTICAS.');
    END IF;
END TRG_AV_JP_RM_BE_VAL_KDA_JUGADOR;
/

