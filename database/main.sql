-- GESTOR 5: ASIGNACIÓN DE PREMIOS A EQUIPOS GANADORES
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_GEST_ASIG_PREMIO (
    P_ID_TORNEO IN NUMBER,
    P_ID_EQUIPO IN NUMBER,
    P_ID_PREMIO IN NUMBER
) IS
    V_INSCRITO NUMBER;
    V_MONTO    AV_JP_RM_BE_PREMIOS.MONTO%TYPE;
BEGIN
    SELECT COUNT(*) INTO V_INSCRITO
    FROM AV_JP_RM_BE_INSCRIPCIONES
    WHERE ID_TORNEO = P_ID_TORNEO AND ID_EQUIPO = P_ID_EQUIPO;

    IF V_INSCRITO = 0 THEN
        RAISE_APPLICATION_ERROR(-20027, 'EL EQUIPO NO ESTÁ INSCRITO EN ESTE TORNEO.');
    END IF;

    SELECT MONTO INTO V_MONTO
    FROM AV_JP_RM_BE_PREMIOS
    WHERE ID_PREMIO = P_ID_PREMIO;

    INSERT INTO AV_JP_RM_BE_ASIGNACION_PREMIOS (
        ID_ASIGNACION, FECHA, MONTO_ENTREGADO, ID_TORNEO, ID_EQUIPO, ID_PREMIO
    ) VALUES (
        SEQ_AV_JP_RM_BE_ASIG_PREMIOS.NEXTVAL, SYSDATE, V_MONTO, P_ID_TORNEO, P_ID_EQUIPO, P_ID_PREMIO
    );
    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20028, 'EL PREMIO SELECCIONADO NO EXISTE.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'ERROR AL ASIGNAR PREMIO: ' || SQLERRM);
END SP_AV_JP_RM_BE_GEST_ASIG_PREMIO;
/

