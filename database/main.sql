-- GESTOR 4: REGISTRO DE SANCIONES (CURSOR EXPLÍCITO)
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_GEST_SANCION (
    P_MOTIVO     IN VARCHAR2,
    P_ID_JUGADOR IN NUMBER,
    P_ID_PARTIDA IN NUMBER
) IS
    CURSOR CUR_AV_JP_RM_BE_HIST_SANCION IS
        SELECT ID_SANCION
        FROM AV_JP_RM_BE_SANCIONES
        WHERE ID_JUGADOR = P_ID_JUGADOR;

    V_ID_SAN   AV_JP_RM_BE_SANCIONES.ID_SANCION%TYPE;
    V_CONTADOR NUMBER := 0;
BEGIN
    OPEN CUR_AV_JP_RM_BE_HIST_SANCION;
    LOOP
        FETCH CUR_AV_JP_RM_BE_HIST_SANCION INTO V_ID_SAN;
        EXIT WHEN CUR_AV_JP_RM_BE_HIST_SANCION%NOTFOUND;
        V_CONTADOR := V_CONTADOR + 1;
    END LOOP;
    CLOSE CUR_AV_JP_RM_BE_HIST_SANCION;

    INSERT INTO AV_JP_RM_BE_SANCIONES (ID_SANCION, MOTIVO, FECHA, ID_JUGADOR, ID_PARTIDA)
    VALUES (SEQ_AV_JP_RM_BE_SANCIONES.NEXTVAL, P_MOTIVO, SYSDATE, P_ID_JUGADOR, P_ID_PARTIDA);
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF CUR_AV_JP_RM_BE_HIST_SANCION%ISOPEN THEN
            CLOSE CUR_AV_JP_RM_BE_HIST_SANCION;
        END IF;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'ERROR AL REGISTRAR SANCIÓN: ' || SQLERRM);
END SP_AV_JP_RM_BE_GEST_SANCION;
/

