-- 0. LIMPIEZA AUTOMÁTICA DE OBJETOS PREVIOS (EVITA DUPLICADOS Y ERRORES)
-- ============================================================================
BEGIN
    -- 1. Eliminar Triggers del proyecto
    FOR trg IN (SELECT trigger_name FROM user_triggers WHERE trigger_name LIKE '%AV_JP_RM_BE_%') LOOP
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || trg.trigger_name;
    END LOOP;

    -- 2. Eliminar Tablas del proyecto en cascada (sin importar el orden de FK)
    FOR tbl IN (SELECT table_name FROM user_tables WHERE table_name LIKE '%AV_JP_RM_BE_%') LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || tbl.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    -- 3. Eliminar Secuencias del proyecto
    FOR seq IN (SELECT sequence_name FROM user_sequences WHERE sequence_name LIKE '%AV_JP_RM_BE_%') LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || seq.sequence_name;
    END LOOP;

    -- 4. Eliminar Procedimientos y Funciones del proyecto
    FOR obj IN (
        SELECT object_name, object_type 
        FROM user_objects 
        WHERE object_type IN ('PROCEDURE', 'FUNCTION') 
          AND object_name LIKE '%AV_JP_RM_BE_%'
    ) LOOP
        EXECUTE IMMEDIATE 'DROP ' || obj.object_type || ' ' || obj.object_name;
    END LOOP;
END;
