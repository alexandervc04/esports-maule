-- REPORTE 2: RANKING DE JUGADORES MVP
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_REP_RANKING_MVP (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT J.ID_JUGADOR, J.NICK, E.NOMBRE AS EQUIPO, E.TAG,
               COUNT(K.ID_KDA) AS PARTIDAS_JUGADAS,
               NVL(SUM(K.KILLS), 0) AS TOTAL_KILLS,
               NVL(SUM(K.DEATHS), 0) AS TOTAL_DEATHS,
               NVL(SUM(K.ASSISTS), 0) AS TOTAL_ASSISTS,
               FN_AV_JP_RM_BE_CALCULAR_KDA(
                   NVL(SUM(K.KILLS), 0), NVL(SUM(K.DEATHS), 0), NVL(SUM(K.ASSISTS), 0)
               ) AS KDA_GLOBAL,
               FN_AV_JP_RM_BE_CONTAR_SANCIONES(J.ID_JUGADOR) AS SANCIONES
        FROM AV_JP_RM_BE_JUGADORES J
        INNER JOIN AV_JP_RM_BE_EQUIPOS E ON J.ID_EQUIPO = E.ID_EQUIPO
        LEFT JOIN AV_JP_RM_BE_DETALLE_ESTADISTICAS_KDA K ON J.ID_JUGADOR = K.ID_JUGADOR
        GROUP BY J.ID_JUGADOR, J.NICK, E.NOMBRE, E.TAG
        ORDER BY KDA_GLOBAL DESC, TOTAL_KILLS DESC;
END SP_AV_JP_RM_BE_REP_RANKING_MVP;
/

-- REPORTE 3: OCUPACIÓN DE SEDES, CUPOS Y PREMIOS POR TORNEO
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_REP_OCUP_TORNEOS (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT T.ID_TORNEO, T.NOMBRE AS TORNEO, S.NOMBRE AS SEDE,
               T.MAX_CUPOS,
               (T.MAX_CUPOS - FN_AV_JP_RM_BE_CUPOS_DISPONIBLES(T.ID_TORNEO)) AS CUPOS_OCUPADOS,
               FN_AV_JP_RM_BE_CUPOS_DISPONIBLES(T.ID_TORNEO) AS CUPOS_DISPONIBLES,
               NVL(SUM(AP.MONTO_ENTREGADO), 0) AS PREMIOS_REPARTIDOS
        FROM AV_JP_RM_BE_TORNEOS T
        INNER JOIN AV_JP_RM_BE_SEDES S ON T.ID_SEDE = S.ID_SEDE
        LEFT JOIN AV_JP_RM_BE_ASIGNACION_PREMIOS AP ON T.ID_TORNEO = AP.ID_TORNEO
        GROUP BY T.ID_TORNEO, T.NOMBRE, S.NOMBRE, T.MAX_CUPOS
        ORDER BY T.ID_TORNEO;
END SP_AV_JP_RM_BE_REP_OCUP_TORNEOS;
/

