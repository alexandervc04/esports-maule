-- REPORTE 1: RENDIMIENTO Y CONVOCATORIA POR VIDEOJUEGO
CREATE OR REPLACE PROCEDURE SP_AV_JP_RM_BE_REP_REND_JUEGOS (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT J.ID_JUEGO, J.NOMBRE AS JUEGO, J.GENERO,
               COUNT(DISTINCT T.ID_TORNEO) AS TOTAL_TORNEOS,
               COUNT(DISTINCT I.ID_INSCRIPCION) AS EQUIPOS_INSCRITOS
        FROM AV_JP_RM_BE_JUEGOS J
        LEFT JOIN AV_JP_RM_BE_TORNEOS T ON J.ID_JUEGO = T.ID_JUEGO
        LEFT JOIN AV_JP_RM_BE_INSCRIPCIONES I ON T.ID_TORNEO = I.ID_TORNEO
        GROUP BY J.ID_JUEGO, J.NOMBRE, J.GENERO
        ORDER BY EQUIPOS_INSCRITOS DESC, TOTAL_TORNEOS DESC;
END SP_AV_JP_RM_BE_REP_REND_JUEGOS;
