  CREATE OR REPLACE EDITIONABLE PROCEDURE "SP_AV_JP_RM_BE_GEST_GEN_PARTIDAS" (
    P_ID_TORNEO  IN NUMBER,
    P_ID_ARBITRO IN NUMBER,
    P_FECHA      IN DATE
) IS
    CURSOR CUR_AV_JP_RM_BE_EQ_TORNEO IS
        SELECT E.ID_EQUIPO, E.TAG
        FROM AV_JP_RM_BE_INSCRIPCIONES I
        INNER JOIN AV_JP_RM_BE_EQUIPOS E ON I.ID_EQUIPO = E.ID_EQUIPO
        WHERE I.ID_TORNEO = P_ID_TORNEO
          AND UPPER(I.ESTADO) = 'CONFIRMADA'
        ORDER BY I.ID_INSCRIPCION;

    V_ID_EQ1  AV_JP_RM_BE_EQUIPOS.ID_EQUIPO%TYPE;
    V_TAG_EQ1 AV_JP_RM_BE_EQUIPOS.TAG%TYPE;
    V_ID_EQ2  AV_JP_RM_BE_EQUIPOS.ID_EQUIPO%TYPE;
    V_TAG_EQ2 AV_JP_RM_BE_EQUIPOS.TAG%TYPE;
    V_CREADAS NUMBER := 0;
BEGIN
    OPEN CUR_AV_JP_RM_BE_EQ_TORNEO;
    LOOP
        FETCH CUR_AV_JP_RM_BE_EQ_TORNEO INTO V_ID_EQ1, V_TAG_EQ1;
        EXIT WHEN CUR_AV_JP_RM_BE_EQ_TORNEO%NOTFOUND;

        FETCH CUR_AV_JP_RM_BE_EQ_TORNEO INTO V_ID_EQ2, V_TAG_EQ2;
        EXIT WHEN CUR_AV_JP_RM_BE_EQ_TORNEO%NOTFOUND;

        INSERT INTO AV_JP_RM_BE_PARTIDAS (ID_PARTIDA, FECHA, RESULTADO, ID_TORNEO, ID_ARBITRO)
        VALUES (
            SEQ_AV_JP_RM_BE_PARTIDAS.NEXTVAL,
            P_FECHA,
            'PENDIENTE (' || V_TAG_EQ1 || ' VS ' || V_TAG_EQ2 || ')',
            P_ID_TORNEO,
            P_ID_ARBITRO
        );
        V_CREADAS := V_CREADAS + 1;
    END LOOP;
    CLOSE CUR_AV_JP_RM_BE_EQ_TORNEO;

    IF V_CREADAS = 0 THEN
        RAISE_APPLICATION_ERROR(-20024, 'SE REQUIEREN AL MENOS 2 EQUIPOS CONFIRMADOS PARA GENERAR PARTIDAS.');
    END IF;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF CUR_AV_JP_RM_BE_EQ_TORNEO%ISOPEN THEN
            CLOSE CUR_AV_JP_RM_BE_EQ_TORNEO;
        END IF;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'ERROR AL GENERAR PARTIDAS: ' || SQLERRM);
END SP_AV_JP_RM_BE_GEST_GEN_PARTIDAS;
