  CREATE OR REPLACE EDITIONABLE PROCEDURE "SP_AV_JP_RM_BE_REP_OCUP_TORNEOS" (
    P_CURSOR OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT T.ID_TORNEO, T.NOMBRE AS TORNEO, S.NOMBRE AS SEDE,
               T.MAX_CUPOS,
               (T.MAX_CUPOS - FN_AV_JP_RM_BE_CUPOS_DISPONIBLES(T.ID_TORNEO)) AS CUPOS_OCUPADOS,
               FN_AV_JP_RM_BE_CUPOS_DISPONIBLES(T.ID_TORNEO) AS CUPOS_DISPONIBLES,
               NVL(SUM(AP.MONTO_ENTREGADO), 0) AS PREMIOS_REPARTIDOS
        FROM AV_JP_RM_BE_TORNEOS T
        INNER JOIN AV_JP_RM_BE_SEDES S ON T.ID_SEDE = S.ID_SEDE
        LEFT JOIN AV_JP_RM_BE_ASIGNACION_PREMIOS AP ON T.ID_TORNEO = AP.ID_TORNEO
        GROUP BY T.ID_TORNEO, T.NOMBRE, S.NOMBRE, T.MAX_CUPOS
        ORDER BY T.ID_TORNEO;
END SP_AV_JP_RM_BE_REP_OCUP_TORNEOS;
