--  DDL for Function FN_AV_JP_RM_BE_CALCULAR_KDA
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "FN_AV_JP_RM_BE_CALCULAR_KDA" (
    P_KILLS   IN NUMBER,
    P_DEATHS  IN NUMBER,
    P_ASSIS IN NUMBER
) RETURN NUMBER IS
    V_KDA NUMBER(10, 2);
BEGIN
    IF P_DEATHS <= 0 THEN
        V_KDA := P_KILLS + P_ASSIS;
    ELSE
        V_KDA := ROUND((P_KILLS + P_ASSIS) / P_DEATHS, 2);
    END IF;
    RETURN V_KDA;
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END FN_AV_JP_RM_BE_CALCULAR_KDA;
